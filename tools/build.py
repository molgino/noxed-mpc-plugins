def make_slug(name):
    return re.sub(r"[^a-z0-9]", "-", name.lower())


def legal_filename(s):
    return "".join(c for c in s if c not in ILLEGAL_FILENAME_CHARS)


def output_folder_name(manifest):
    return legal_filename("%s - VST - %s" % (manifest["manufacturer"], manifest["name"]))


def pad_version(version):
    """'1.0.0' -> '1.0.0.0'. Non-numeric parts are reduced to their leading digits (or 0)."""
    parts = []
    for p in str(version).strip().split("."):
        m = re.match(r"\d+", p)
        parts.append(m.group(0) if m else "0")
    if len(parts) > 4:
        warn("plugin.json version '%s' has more than 4 components; using the first 4 in version.xml" % version)
        parts = parts[:4]
    while len(parts) < 4:
        parts.append("0")
    return ".".join(parts)


