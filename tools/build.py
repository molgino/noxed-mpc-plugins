def parse_args(argv):
    ap = argparse.ArgumentParser(
        description="Build an MPC plugin project into a deployable '<Manufacturer> - VST - <Name>' folder.",
        epilog="Environment: ZIG=<path to zig, or to a python that has 'pip install ziglang'> selects a zig to use.")
    ap.add_argument("project", help="plugin project folder (contains plugin.json and src/)")
    ap.add_argument("--target", choices=["all", "arm32", "arm64", "native", "desktop"], default="all",
                    help="what to build (default: all = native + arm32 + arm64 + output folder; desktop = a generic "
                         "VST2 with no UI for hosts on this computer, e.g. Reaper, into build/desktop/)")
    ap.add_argument("--toolchain", choices=["zig", "gcc", "docker"], default="zig",
                    help="zig (default, downloads itself), gcc (system cross compilers), docker (tools/docker image)")
    ap.add_argument("--debug", action="store_true", help="build with -O0 -g and keep symbols")
    ap.add_argument("--no-ui", action="store_true", help="do not generate Plugin Skins (skins/ is still copied if present)")
    ap.add_argument("--no-validate", action="store_true", help="skip tools/validate.py at the end")
    ap.add_argument("--define", action="append", metavar="NAME=VALUE", help="extra -D preprocessor define (repeatable)")
    ap.add_argument("--verbose", action="store_true", help="print every command line")
    ap.add_argument("--zig", metavar="PATH", help="zig executable (or a python interpreter that has the ziglang package)")
    return ap.parse_args(argv)


def main(argv=None):
    global VERBOSE
    args = parse_args(argv)
    VERBOSE = args.verbose

    project = os.path.abspath(args.project)
    if not os.path.isdir(project):
        log("ERROR: project folder not found: %s" % project)
        return 1

    try:
        manifest = load_manifest(project)
        slug = make_slug(manifest["name"])
        folder = output_folder_name(manifest)
        build_dir = os.path.join(project, "build")
        out_dir = os.path.join(build_dir, folder)
        params_json = os.path.join(build_dir, "params.json")
        native_ext = ".dylib" if IS_MAC else (".dll" if IS_WINDOWS else ".so")
        native_lib = os.path.join(build_dir, "native", slug + native_ext)

        log("Building %s by %s  (%s)" % (manifest["name"], manifest["manufacturer"], project))
        log("  toolchain: %s   target: %s   %s" % (args.toolchain, args.target, "debug" if args.debug else "release"))

        builder = Builder(args, project, manifest)
        if args.target == "desktop":
            step(1, 1, "Desktop VST2 for this computer (%s)" % ("macOS" if IS_MAC else "Windows" if IS_WINDOWS else "Linux"))
            result = builder.build_desktop(slug, folder)
            log("")
            log("=" * 72)
            log("Desktop build finished: %s" % result)
            if IS_MAC:
                log("  Copy the .vst to ~/Library/Audio/Plug-Ins/VST/ (or /Library/Audio/Plug-Ins/VST/), then rescan plugins in your host.")
            elif IS_WINDOWS:
                log("  Copy the folder into your host's VST2 plugin folder (e.g. C:\\Program Files\\VSTPlugins), then rescan plugins.")
            else:
                log("  Copy the folder into ~/.vst (or your host's VST2 folder), then rescan plugins.")
            log("  There is no touch UI: the host shows its own parameter list. Only VST2 hosts will load it (Reaper, MPC Software, ...).")
            return finish(0)
        arm_targets = [] if args.target == "native" else (["arm32", "arm64"] if args.target == "all" else [args.target])
        total = 2 + len(arm_targets) + (3 if arm_targets else 0)
        n = 0

        # 1. native build ---------------------------------------------------
        n += 1
        step(n, total, "Native build (for host_sim and testing on this computer)")
        native_ok = builder.build_native(native_lib)

        # 2. host_sim dump --------------------------------------------------
        n += 1
        step(n, total, "Parameter dump (host_sim) -> build/params.json")
        params_ok = False
        if native_ok:
            params_ok = builder.dump_params(native_lib, params_json)
        else:
            log("  skipped (no native build)")
        if not params_ok and os.path.isfile(params_json):
            warn("using the params.json from a previous build")

        # 3/4. ARM builds ---------------------------------------------------
        for target in arm_targets:
            n += 1
            step(n, total, "%s build (%s)" % (target, "MPC Live/X/One (32-bit)" if target == "arm32" else "MPC Live II/One+/Key 61/X SE/3 (64-bit)"))
            key, suffix = ARM_TARGETS[target][4], ARM_TARGETS[target][5]
            rel = manifest.get(key)
            if not isinstance(rel, str) or not rel.strip():
                rel = "VST/" + slug + suffix
                warn("plugin.json has no \"%s\"; using \"%s\" (add it to plugin.json so the MPC finds the library)" % (key, rel))
            output = os.path.normpath(os.path.join(out_dir, rel.replace("/", os.sep)))
            builder.build_arm(target, output)

        if not arm_targets:
            log("")
            log("Native build only: %s" % native_lib)
            host_sim = builder.host_sim_path()
            if os.path.isfile(host_sim):
                log("Try it:  %s %s test --notes 60,64,67 --wav out.wav" % (quote_cmd([host_sim]), quote_cmd([native_lib])))
            return finish(0)

        # 5. assemble -------------------------------------------------------
        n += 1
        step(n, total, "Assemble output folder: build/%s/" % folder)
        os.makedirs(out_dir, exist_ok=True)
        shutil.copyfile(os.path.join(project, "plugin.json"), os.path.join(out_dir, "plugin.json"))
        log("  copied plugin.json")
        has_skins = make_skins(project, out_dir, params_json, args.no_ui)
        n_content = copy_content(project, out_dir)
        if n_content:
            log("  copied %d file%s from Content/ into Content/" % (n_content, "" if n_content == 1 else "s"))

        # 6. version.xml ----------------------------------------------------
        n += 1
        step(n, total, "version.xml")
        write_version_xml(out_dir, manifest, has_skins)
        log("  version %s%s" % (pad_version(manifest["version"]), ", uiversion 0.1.0.0" if has_skins else " (no Plugin Skins, so no uiversion)"))

        # 7. validate -------------------------------------------------------
        n += 1
        step(n, total, "Validate")
        valid = True
        if args.no_validate:
            log("  skipped (--no-validate)")
        else:
            valid = validate(out_dir, params_json)

        # summary -----------------------------------------------------------
        log("")
        log("=" * 72)
        if valid:
            log("Build finished: %s" % folder)
        else:
            log("Build finished WITH VALIDATION ERRORS: %s" % folder)
        log("  Output folder: %s" % out_dir)
        for root, dirs, files in os.walk(out_dir):
            dirs.sort()
            for f in sorted(files):
                p = os.path.join(root, f)
                log("    %-40s %s" % (os.path.relpath(p, out_dir).replace(os.sep, "/"), human_size(p)))
        if native_ok:
            log("  Native test build: %s" % native_lib)
        log("")
        log("Next:")
        log("  * Make a zip for sharing:   python %s %s" % (os.path.join("tools", "package.py"), quote_cmd([os.path.relpath(project) if not os.path.relpath(project).startswith("..") else project])))
        log("  * Or copy the output folder into a folder named \"VST2 Plugins\" on your MPC's drive (see INSTALL.txt in the zip).")
        return finish(0 if valid else 1)

    except BuildError as e:
        log("")
        log("ERROR: %s" % e)
        return finish(1)
    except KeyboardInterrupt:
        log("\nInterrupted.")
        return 130


def finish(code):
    if WARNINGS:
        log("")
        log("%d warning%s:" % (len(WARNINGS), "" if len(WARNINGS) == 1 else "s"))
        for w in WARNINGS:
            log("  - " + w.splitlines()[0])
    return code


if __name__ == "__main__":
    sys.exit(main())
