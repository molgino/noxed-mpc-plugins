def copy_tree_verbatim(src, dst):
    if os.path.isdir(dst):
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns(".DS_Store", "Thumbs.db"))


def run_tool(name, argv):
    """Runs a sibling python tool. Returns (status, output): status is 'ok', 'failed' or 'missing'."""
    script = os.path.join(TOOLS_DIR, name)
    if not os.path.isfile(script):
        return "missing", ""
    code, out = run([sys.executable, script] + argv)
    return ("ok" if code == 0 else "failed:%d" % code), out


def _xml_escape(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def copy_content(project, dst_folder):
    """Copy <project>/Content/ to <dst_folder>/Content/ (samples, wavetables, ...). Returns the file count."""
    src = os.path.join(project, "Content")
    dst = os.path.join(dst_folder, "Content")
    if not os.path.isdir(src):
        if os.path.isdir(dst):
            shutil.rmtree(dst)
        return 0
    copy_tree_verbatim(src, dst)
    return sum(len(files) for _r, _d, files in os.walk(dst))


def make_skins(project, out_dir, params_json, no_ui):
    """Returns True when <out_dir>/Plugin Skins/TUI.json exists afterwards."""
    skins_out = os.path.join(out_dir, "Plugin Skins")
    skins_src = os.path.join(project, "skins")
    if os.path.isdir(skins_out):
        shutil.rmtree(skins_out)

    if os.path.isdir(skins_src):
        log("  copying hand-written skins/ -> Plugin Skins/ (gen_ui.py not run)")
        copy_tree_verbatim(skins_src, skins_out)
        if not os.path.isfile(os.path.join(skins_out, "TUI.json")):
            warn("skins/ has no TUI.json; the MPC will show its generic parameter UI")
    elif no_ui:
        log("  --no-ui: no Plugin Skins (the MPC shows its generic parameter UI)")
    elif not os.path.isfile(params_json):
        warn("build/params.json is missing, so gen_ui.py cannot run; no Plugin Skins generated "
             "(the MPC shows its generic parameter UI)")
    else:
        ui_json = os.path.join(project, "ui.json")
        argv = ["--params", params_json, "--out", skins_out, "--kit-cache", os.path.join(project, "build")]
        if os.path.isfile(ui_json):
            argv += ["--ui", ui_json]
            log("  gen_ui.py (ui.json) -> Plugin Skins/")
        else:
            log("  gen_ui.py (no ui.json: automatic pages) -> Plugin Skins/")
        status, out = run_tool("gen_ui.py", argv)
        if status == "missing":
            warn("tools/gen_ui.py is missing; no Plugin Skins generated (the MPC shows its generic parameter UI)")
        elif status != "ok":
            if out.strip():
                log(out.rstrip())
            warn("gen_ui.py failed (%s); no Plugin Skins generated (the MPC shows its generic parameter UI)" % status)
            if os.path.isdir(skins_out):
                shutil.rmtree(skins_out)
        elif out.strip():
            for line in out.rstrip().splitlines():
                if VERBOSE or "NOTE" in line or "WARNING" in line:
                    log("  " + line)

    assets_src = os.path.join(project, "assets")
    if os.path.isdir(assets_src):
        if os.path.isdir(skins_out):
            n = 0
            for root, _dirs, files in os.walk(assets_src):
                rel = os.path.relpath(root, assets_src)
                for f in files:
                    if f in (".DS_Store", "Thumbs.db"):
                        continue
                    dst = os.path.join(skins_out, rel, f) if rel != "." else os.path.join(skins_out, f)
                    os.makedirs(os.path.dirname(dst), exist_ok=True)
                    shutil.copyfile(os.path.join(root, f), dst)
                    n += 1
            log("  copied %d asset file%s from assets/ into Plugin Skins/" % (n, "" if n == 1 else "s"))
        else:
            warn("assets/ was not copied because there is no Plugin Skins folder to put it in")

    return os.path.isfile(os.path.join(skins_out, "TUI.json"))


def write_version_xml(out_dir, manifest, has_skins):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<plugincontent version="1.0">',
             '    <version>%s</version>' % pad_version(manifest["version"])]
    if has_skins:
        lines.append('    <uiversion>0.1.0.0</uiversion>')
    lines.append('</plugincontent>')
    with open(os.path.join(out_dir, "version.xml"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines) + "\n")


def validate(out_dir, params_json):
    """Returns True if validation passed or could not run; False if validate.py reported errors."""
    argv = [out_dir]
    if os.path.isfile(params_json):
        argv += ["--params", params_json]
    status, out = run_tool("validate.py", argv)
    if status == "missing":
        warn("tools/validate.py is missing; skipping validation")
        return True
    if out.strip():
        log(out.rstrip())
    if status == "ok":
        return True
    if status == "failed:1":
        log("ERROR: validate.py reported problems with the output folder (see above).")
        return False
    warn("validate.py did not run properly (%s); skipping validation" % status)
    return True


