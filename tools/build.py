class BuildError(Exception):
    pass


VERBOSE = False
WARNINGS = []


def log(msg=""):
    print(msg, flush=True)


def step(n, total, msg):
    log("")
    log("[%d/%d] %s" % (n, total, msg))


def warn(msg):
    WARNINGS.append(msg)
    log("WARNING: " + msg)


def detail(msg):
    if VERBOSE:
        log("    " + msg)


def quote_cmd(argv):
    out = []
    for a in argv:
        out.append('"%s"' % a if (" " in a or '"' in a) else a)
    return " ".join(out)


def run(argv, cwd=None, capture=True, env=None):
    """Run a command. Returns (returncode, combined output). Never raises for a non-zero exit."""
    detail("$ " + quote_cmd(argv))
    try:
        if capture:
            p = subprocess.run(argv, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=env)
            return p.returncode, p.stdout.decode("utf-8", errors="replace")
        p = subprocess.run(argv, cwd=cwd, env=env)
        return p.returncode, ""
    except FileNotFoundError as e:
        return 127, "command not found: %s (%s)" % (argv[0], e)
    except OSError as e:
        return 126, "could not run %s: %s" % (argv[0], e)


def human_size(path):
    try:
        n = os.path.getsize(path)
    except OSError:
        return "?"
    if n < 1024:
        return "%d B" % n
    if n < 1024 * 1024:
        return "%.0f KB" % (n / 1024.0)
    return "%.1f MB" % (n / (1024.0 * 1024.0))


