def zig_argv_from_path(path):
    """A path to a zig executable, or to a python interpreter that has the ziglang package."""
    base = os.path.basename(path).lower()
    if base.startswith("python"):
        return [path, "-m", "ziglang"]
    return [path]


def zig_works(argv):
    code, out = run(argv + ["version"])
    return code == 0 and out.strip() != "", out.strip()


def venv_python(venv_dir):
    if IS_WINDOWS:
        return os.path.join(venv_dir, "Scripts", "python.exe")
    return os.path.join(venv_dir, "bin", "python")


def find_zig(explicit=None):
    """Returns the argv prefix that runs zig (e.g. ['zig'] or ['.../python', '-m', 'ziglang'])."""
    candidates = []
    if explicit:
        candidates.append(("--zig", zig_argv_from_path(explicit)))
    if os.environ.get("ZIG"):
        candidates.append(("$ZIG", zig_argv_from_path(os.environ["ZIG"])))
    on_path = shutil.which("zig")
    if on_path:
        candidates.append(("PATH", [on_path]))
    venv_dir = os.path.join(SDK_TOOLS_DIR, "zigenv")
    vpy = venv_python(venv_dir)
    if os.path.isfile(vpy):
        candidates.append((venv_dir, [vpy, "-m", "ziglang"]))

    for origin, argv in candidates:
        ok, ver = zig_works(argv)
        if ok:
            log("Using zig %s (from %s)" % (ver, origin))
            return argv
        warn("zig at %s does not work (%s); trying the next option" % (origin, quote_cmd(argv)))

    # Nothing usable: install ziglang into a private venv.
    log("zig was not found on PATH. Installing the 'ziglang' Python package into a private")
    log("virtual environment (one-time, needs network): %s" % venv_dir)
    os.makedirs(SDK_TOOLS_DIR, exist_ok=True)
    if not os.path.isfile(vpy):
        log("  Creating venv: %s -m venv %s" % (sys.executable, venv_dir))
        code, out = run([sys.executable, "-m", "venv", venv_dir])
        if code != 0 or not os.path.isfile(vpy):
            raise BuildError("Could not create a virtual environment:\n%s\n%s" % (out, zig_install_help()))
    log("  Installing: %s -m pip install ziglang" % vpy)
    code, out = run([vpy, "-m", "pip", "install", "--disable-pip-version-check", "ziglang"])
    if code != 0:
        log(out)
        raise BuildError("pip install ziglang failed.\n" + zig_install_help())
    argv = [vpy, "-m", "ziglang"]
    ok, ver = zig_works(argv)
    if not ok:
        raise BuildError("ziglang was installed but does not run: %s\n%s" % (quote_cmd(argv), zig_install_help()))
    log("Installed zig %s" % ver)
    return argv


def zig_install_help():
    return ("How to get zig (any ONE of these):\n"
            "  * pip install ziglang           then:  build.py --zig <path to that python>   (or set ZIG=<path>)\n"
            "  * download zig from https://ziglang.org/download/ and put it on your PATH (or use --zig <path>/zig)\n"
            "  * macOS: brew install zig        Linux: snap install zig --classic --beta   Windows: winget install zig.zig\n"
            "  * or use --toolchain gcc (needs arm-linux-gnueabihf-g++ and aarch64-linux-gnu-g++) or --toolchain docker")


def find_system_cxx():
    for name in ("c++", "g++", "clang++"):
        p = shutil.which(name)
        if p:
            return [p]
    return None


def native_target_flags_for_zig():
    """zig's native target on Windows may pick the MSVC ABI; be explicit about the GNU one."""
    if not IS_WINDOWS:
        return []
    machine = platform.machine().lower()
    if machine in ("arm64", "aarch64"):
        return ["-target", "aarch64-windows-gnu"]
    return ["-target", "x86_64-windows-gnu"]


class Docker:
    """Runs cross compilers inside the tools/docker image, translating host paths."""

    def __init__(self, project):
        self.exe = shutil.which("docker") or shutil.which("podman")
        if not self.exe:
            raise BuildError("--toolchain docker needs 'docker' or 'podman' on your PATH.\n"
                             "  Install Docker Desktop (https://www.docker.com/) or Podman (https://podman.io/).")
        self.project = os.path.abspath(project)
        self.mounts = [(os.path.abspath(SDK_ROOT), "/sdk")]
        if not (self.project + os.sep).startswith(os.path.abspath(SDK_ROOT) + os.sep):
            self.mounts.append((self.project, "/project"))
        # longest host path first so nested paths translate correctly
        self.mounts.sort(key=lambda m: -len(m[0]))

    def ensure_image(self):
        code, _ = run([self.exe, "image", "inspect", DOCKER_IMAGE])
        if code == 0:
            return
        log("Building the cross-compiler container image '%s' (one-time, needs network, takes a few minutes)..." % DOCKER_IMAGE)
        code, out = run([self.exe, "build", "-t", DOCKER_IMAGE, DOCKER_DIR], capture=False)
        if code != 0:
            raise BuildError("Building the docker image failed. See %s/README.md" % DOCKER_DIR)

    def translate(self, arg):
        a = arg
        for host, guest in self.mounts:
            variants = [host]
            if IS_WINDOWS:
                variants.append(host.replace("\\", "/"))
            for h in variants:
                if h in a:
                    a = a.replace(h, guest)
        if IS_WINDOWS and ("/sdk" in a or "/project" in a):
            a = a.replace("\\", "/")
        return a

    def wrap(self, argv):
        cmd = [self.exe, "run", "--rm"]
        for host, guest in self.mounts:
            cmd += ["-v", "%s:%s" % (host, guest)]
        if not IS_WINDOWS and hasattr(os, "getuid"):
            cmd += ["--user", "%d:%d" % (os.getuid(), os.getgid())]
        cmd += ["-w", "/sdk", DOCKER_IMAGE]
        return cmd + [self.translate(a) for a in argv]


