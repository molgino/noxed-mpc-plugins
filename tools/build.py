#!/usr/bin/env python3
"""Build an MPC plugin project into a deployable "<Manufacturer> - VST - <Name>" folder.

Usage:
    python tools/build.py <project> [--target all|arm32|arm64|native] [--toolchain zig|gcc|docker]
                                    [--debug] [--no-ui] [--no-validate] [--define NAME=VALUE]
                                    [--verbose] [--zig PATH]

Steps (in order):
    1. native build            -> <project>/build/native/<slug>.(dylib|so|dll)   (for host_sim / testing)
    2. host_sim dump           -> <project>/build/params.json
    3. arm32 build             -> <output folder>/VST/<slug>-arm32.so
    4. arm64 build             -> <output folder>/VST/<slug>-arm64.so
    desktop (--target desktop): instead of steps 2-7, builds a generic VST2 for THIS computer (no UI, the host shows
                               its own parameter list) -> <project>/build/desktop/  (see build_desktop)
    5. assemble output folder  -> plugin.json (verbatim), Plugin Skins/ (copied from skins/ or generated by gen_ui.py),
                                  Content/ (copied verbatim from <project>/Content/ if it exists)
    6. version.xml
    7. validate.py

Toolchain (default "zig"): `zig` on PATH, else $ZIG / --zig, else <sdk>/.sdk-tools/zigenv (created automatically
with `python -m venv` + `pip install ziglang` the first time; needs network once).

Exit codes: 0 = success, 1 = compile failure / validation errors / missing project, 2 = bad arguments.
Standard library only. Python 3.9+.
"""

import argparse
import json
import os
import platform
import re
import shutil
import subprocess
import sys
import time

SDK_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOOLS_DIR = os.path.join(SDK_ROOT, "tools")
FRAMEWORK_DIR = os.path.join(SDK_ROOT, "framework")
SDK_TOOLS_DIR = os.path.join(SDK_ROOT, ".sdk-tools")
EXPORTS_MAP = os.path.join(TOOLS_DIR, "exports.map")
HOST_SIM_SRC = os.path.join(TOOLS_DIR, "host-sim", "host_sim.cpp")
DOCKER_DIR = os.path.join(TOOLS_DIR, "docker")
DOCKER_IMAGE = "mpc-plugin-sdk-cross"

IS_WINDOWS = os.name == "nt"
IS_MAC = sys.platform == "darwin"

ILLEGAL_FILENAME_CHARS = '"#@,;:<>*^|?\\/'  # the exact set the MPC strips when it builds the folder name

COMMON_FLAGS = [
    "-std=c++17", "-fPIC", "-shared",
    "-fvisibility=hidden", "-fvisibility-inlines-hidden",
    "-ffunction-sections", "-fdata-sections",
    "-Wall", "-Wextra",
]

ARM_TARGETS = {
    # name: (zig -target, zig -mcpu, gcc compiler, gcc arch flags, manifest key, default file name suffix)
    "arm32": ("arm-linux-gnueabihf.2.31", "cortex_a17", "arm-linux-gnueabihf-g++",
              ["-march=armv7-a", "-mfpu=neon-vfpv4", "-mfloat-abi=hard"], "file32", "-arm32.so"),
    "arm64": ("aarch64-linux-gnu.2.31", "cortex_a55", "aarch64-linux-gnu-g++",
              ["-march=armv8-a"], "file64", "-arm64.so"),
}


