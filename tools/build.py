class Builder:
    def __init__(self, args, project, manifest):
        self.args = args
        self.project = project
        self.manifest = manifest
        self.sources = find_sources(project)
        self.toolchain = args.toolchain
        self.zig = None
        self.docker = None
        self.system_cxx = None
        self.version_script_ok = os.path.isfile(EXPORTS_MAP)
        if not self.version_script_ok:
            warn("tools/exports.map is missing; building without a linker version script")

        if self.toolchain == "zig":
            self.zig = find_zig(args.zig)
        elif self.toolchain == "docker":
            self.docker = Docker(project)
            self.system_cxx = find_system_cxx()
        elif self.toolchain == "gcc":
            self.system_cxx = find_system_cxx()

    # --- flag assembly ------------------------------------------------------
    def common_flags(self):
        flags = list(COMMON_FLAGS)
        flags.append("-O0" if self.args.debug else "-O2")
        if self.args.debug:
            flags.append("-g")
        flags.append("-I" + FRAMEWORK_DIR)
        flags.append("-I" + os.path.join(self.project, "src"))
        for d in self.args.define or []:
            flags.append("-D" + d)
        return flags

    def link_flags_arm(self):
        flags = ["-Wl,--gc-sections"]
        if not self.args.debug:
            flags.append("-Wl,-s")
        return flags

    # --- running the compiler ----------------------------------------------
    def compile(self, label, argv, output, allow_version_script_retry=False):
        """Runs a compiler command line. Prints compiler output verbatim. Raises BuildError on failure."""
        os.makedirs(os.path.dirname(output), exist_ok=True)
        log("  [%s] compiling %d source file%s -> %s" % (
            label, len(self.sources), "" if len(self.sources) == 1 else "s", os.path.relpath(output, self.project)))
        t0 = time.time()
        code, out = run(argv)
        if code != 0 and allow_version_script_retry and self.version_script_ok and _mentions_version_script(out):
            warn("the linker rejected the version script (tools/exports.map); retrying without it")
            self.version_script_ok = False
            argv = [a for a in argv if "--version-script" not in a]
            code, out = run(argv)
        if out.strip():
            log(out.rstrip())
        if code != 0:
            raise BuildError("%s build failed (compiler exit code %d). The compiler messages above say what is wrong.\n"
                             "  Command: %s" % (label, code, quote_cmd(argv)))
        if not os.path.isfile(output):
            raise BuildError("%s build reported success but %s was not created" % (label, output))
        log("  [%s] ok (%s, %.1fs)" % (label, human_size(output), time.time() - t0))

    def build_native(self, output):
        flags = self.common_flags()
        if self.toolchain == "zig":
            argv = self.zig + ["c++"] + flags + native_target_flags_for_zig() + ["-o", output] + self.sources
        else:
            if not self.system_cxx:
                warn("no native C++ compiler found (c++/g++/clang++); skipping the native build and host_sim.\n"
                     "         Install a compiler, or use --toolchain zig, to get parameter dumps and host-sim testing.")
                return False
            argv = self.system_cxx + flags + ["-o", output] + self.sources
            if IS_MAC:
                argv.append("-dynamiclib")
        self.compile("native", argv, output)
        return True

    def build_desktop(self, slug, folder_name):
        """A generic VST2 for this computer, for hosts such as Reaper or MPC Software. No touch UI.

        macOS:         build/desktop/<Name>.vst bundle (universal arm64 + x86_64 when Apple clang is available,
                       ad-hoc signed); files (Content/) live in Contents/Resources.
        Windows/Linux: build/desktop/<Name>/<slug>.dll|so beside plugin.json and Content/; copy the whole folder
                       into the host's VST2 folder.
        Returns the path to copy."""
        base = os.path.join(self.project, "build", "desktop")
        name = legal_filename(self.manifest["name"])
        if os.path.isdir(base):
            shutil.rmtree(base)
        flags = self.common_flags()
        content_dst = None

        if IS_MAC:
            bundle = os.path.join(base, name + ".vst")
            binary = os.path.join(bundle, "Contents", "MacOS", slug)
            content_dst = os.path.join(bundle, "Contents", "Resources")
            clang = find_system_cxx()
            universal = [a for a in flags if a != "-shared"] + ["-bundle", "-arch", "arm64", "-arch", "x86_64"]
            if clang and self.compile_try("desktop", clang + universal + ["-o", binary] + self.sources, binary):
                pass
            else:
                if clang:
                    warn("the universal (arm64 + x86_64) macOS build failed; building for this CPU only")
                if self.toolchain == "zig":
                    argv = self.zig + ["c++"] + flags + ["-o", binary] + self.sources
                elif clang:
                    argv = clang + flags + ["-dynamiclib", "-o", binary] + self.sources
                else:
                    raise BuildError("no C++ compiler found for the desktop build (install Xcode command line tools: xcode-select --install)")
                self.compile("desktop", argv, binary)
            self._write_bundle_files(bundle, slug)
            if shutil.which("codesign"):
                code, out = run(["codesign", "--force", "--sign", "-", bundle])
                if code != 0:
                    warn("codesign failed (%s); Apple Silicon hosts may refuse to load the unsigned plugin" % out.strip())
                else:
                    log("  [desktop] signed (ad-hoc)")
            else:
                warn("codesign not found; Apple Silicon hosts may refuse to load the unsigned plugin")
            result = bundle
        else:
            ext = ".dll" if IS_WINDOWS else ".so"
            folder = os.path.join(base, name)
            binary = os.path.join(folder, slug + ext)
            content_dst = folder
            if self.toolchain == "zig":
                argv = self.zig + ["c++"] + flags + native_target_flags_for_zig()
                if self.version_script_ok and not IS_WINDOWS:
                    argv.append("-Wl,--version-script=" + EXPORTS_MAP)
                argv += ["-o", binary] + self.sources
            else:
                if not self.system_cxx:
                    raise BuildError("no C++ compiler found for the desktop build (install g++ or use the default zig toolchain)")
                argv = self.system_cxx + flags + ["-o", binary] + self.sources
                if self.version_script_ok and not IS_WINDOWS:
                    argv.append("-Wl,--version-script=" + EXPORTS_MAP)
            self.compile("desktop", argv, binary)
            shutil.copyfile(os.path.join(self.project, "plugin.json"), os.path.join(folder, "plugin.json"))
            result = folder

        n = copy_content(self.project, content_dst)
        if n:
            log("  copied %d file%s from Content/" % (n, "" if n == 1 else "s"))
        return result

    def compile_try(self, label, argv, output):
        """Like compile() but returns False instead of raising (compiler messages are shown at -v only)."""
        try:
            self.compile(label, argv, output)
            return True
        except BuildError as e:
            detail(str(e))
            return False

    def _write_bundle_files(self, bundle, slug):
        m = self.manifest
        uid = str(m.get("uid", "????"))
        ident = "com.%s.%s" % (make_slug(str(m.get("manufacturer", "plugin"))), slug)
        plist = ['<?xml version="1.0" encoding="UTF-8"?>',
                 '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
                 '<plist version="1.0"><dict>',
                 '<key>CFBundleDevelopmentRegion</key><string>English</string>',
                 '<key>CFBundleExecutable</key><string>%s</string>' % slug,
                 '<key>CFBundleIdentifier</key><string>%s</string>' % ident,
                 '<key>CFBundleInfoDictionaryVersion</key><string>6.0</string>',
                 '<key>CFBundleName</key><string>%s</string>' % _xml_escape(str(m["name"])),
                 '<key>CFBundlePackageType</key><string>BNDL</string>',
                 '<key>CFBundleSignature</key><string>%s</string>' % _xml_escape(uid[:4].ljust(4, "?")),
                 '<key>CFBundleShortVersionString</key><string>%s</string>' % _xml_escape(str(m.get("version", "1.0.0"))),
                 '<key>CFBundleVersion</key><string>%s</string>' % _xml_escape(str(m.get("version", "1.0.0"))),
                 '</dict></plist>']
        with open(os.path.join(bundle, "Contents", "Info.plist"), "w", encoding="utf-8") as fh:
            fh.write("\n".join(plist) + "\n")
        with open(os.path.join(bundle, "Contents", "PkgInfo"), "w", encoding="ascii", errors="replace") as fh:
            fh.write("BNDL" + uid[:4].ljust(4, "?"))

    def build_arm(self, target, output):
        zig_target, zig_cpu, gcc, gcc_arch, _, _ = ARM_TARGETS[target]
        flags = self.common_flags() + self.link_flags_arm()
        if self.version_script_ok:
            flags.append("-Wl,--version-script=" + EXPORTS_MAP)
        if self.toolchain == "zig":
            argv = self.zig + ["c++"] + flags + ["-target", zig_target, "-mcpu=" + zig_cpu, "-o", output] + self.sources
        else:
            argv = [gcc] + flags + gcc_arch + ["-static-libstdc++", "-static-libgcc", "-o", output] + self.sources
            if self.toolchain == "docker":
                self.docker.ensure_image()
                argv = self.docker.wrap(argv)
            elif not shutil.which(gcc):
                raise BuildError("Cross compiler '%s' not found on PATH.\n"
                                 "  Debian/Ubuntu: sudo apt install g++-arm-linux-gnueabihf g++-aarch64-linux-gnu\n"
                                 "  Or use the default zig toolchain (no --toolchain flag) or --toolchain docker." % gcc)
        self.compile(target, argv, output, allow_version_script_retry=True)

    # --- host_sim ----------------------------------------------------------
    def host_sim_path(self):
        return os.path.join(SDK_TOOLS_DIR, "host_sim.exe" if IS_WINDOWS else "host_sim")

    def ensure_host_sim(self):
        """Builds tools/host-sim/host_sim.cpp into .sdk-tools/ on first use. Returns the path or None."""
        exe = self.host_sim_path()
        if not os.path.isfile(HOST_SIM_SRC):
            warn("tools/host-sim/host_sim.cpp is missing; cannot dump parameters (build/params.json). "
                 "The UI will be generated from an existing params.json if there is one.")
            return None
        deps = [HOST_SIM_SRC, os.path.join(FRAMEWORK_DIR, "mpc_vst2_abi.h")]
        newest_dep = max(os.path.getmtime(d) for d in deps if os.path.isfile(d))
        if os.path.isfile(exe) and os.path.getmtime(exe) >= newest_dep:
            return exe
        log("  building host_sim (first use) -> %s" % exe)
        os.makedirs(SDK_TOOLS_DIR, exist_ok=True)
        flags = ["-std=c++17", "-O2", "-I" + FRAMEWORK_DIR, "-I" + os.path.dirname(HOST_SIM_SRC)]
        if self.zig:
            argv = self.zig + ["c++"] + flags + native_target_flags_for_zig() + ["-o", exe, HOST_SIM_SRC]
        elif self.system_cxx:
            argv = self.system_cxx + flags + ["-o", exe, HOST_SIM_SRC]
        else:
            warn("no compiler available to build host_sim; skipping the parameter dump")
            return None
        if not IS_WINDOWS:
            argv += ["-ldl", "-lpthread"]
            if not IS_MAC:
                argv.append("-lm")
        code, out = run(argv)
        if out.strip():
            log(out.rstrip())
        if code != 0 or not os.path.isfile(exe):
            warn("building host_sim failed (exit %d); skipping the parameter dump. Command: %s" % (code, quote_cmd(argv)))
            return None
        return exe

    def dump_params(self, native_lib, params_json):
        exe = self.ensure_host_sim()
        if exe is None:
            return False
        log("  host_sim dump -> %s" % os.path.relpath(params_json, self.project))
        detail("$ " + quote_cmd([exe, native_lib, "dump"]))
        try:
            p = subprocess.run([exe, native_lib, "dump"], stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=120)
        except subprocess.TimeoutExpired:
            warn("host_sim dump timed out after 120s (does the plugin constructor or prepare() hang?)")
            return False
        except OSError as e:
            warn("could not run host_sim: %s" % e)
            return False
        err = p.stderr.decode("utf-8", errors="replace").strip()
        if p.returncode != 0:
            if err:
                log(err)
            warn("host_sim dump failed (exit %d). The plugin may crash on load - check the messages above." % p.returncode)
            return False
        text = p.stdout.decode("utf-8", errors="replace")
        try:
            data = json.loads(text)
        except ValueError:
            if err:
                log(err)
            warn("host_sim dump did not produce valid JSON; not writing params.json")
            return False
        if VERBOSE and err:
            log(err)
        os.makedirs(os.path.dirname(params_json), exist_ok=True)
        with open(params_json, "w", encoding="utf-8") as fh:
            json.dump(data, fh, indent=2)
            fh.write("\n")
        self.check_manifest_against_dump(data)
        return True

    def check_manifest_against_dump(self, data):
        """Early, friendly cross-checks (validate.py does the thorough job)."""
        m = self.manifest
        if "uid" in m and data.get("uid") not in (None, m["uid"]):
            warn("plugin.json uid \"%s\" differs from the uniqueId compiled into the plugin (\"%s\"). "
                 "The MPC will not match them - make them equal." % (m["uid"], data.get("uid")))
        if data.get("name") not in (None, m["name"]):
            warn("plugin.json name \"%s\" differs from the C++ PluginInfo name \"%s\"; skins and presets are looked up by this name."
                 % (m["name"], data.get("name")))
        if data.get("vendor") not in (None, m["manufacturer"]):
            warn("plugin.json manufacturer \"%s\" differs from the C++ PluginInfo vendor \"%s\"." % (m["manufacturer"], data.get("vendor")))
        kind = m.get("kind")
        if kind in ("instrument", "effect") and "isInstrument" in data:
            if bool(data["isInstrument"]) != (kind == "instrument"):
                warn("plugin.json kind \"%s\" does not match PluginInfo.isInstrument=%s" % (kind, data["isInstrument"]))
        if data.get("numOutputs") == 0:
            warn("the plugin reports 0 outputs; the MPC will not list it")


def _mentions_version_script(out):
    low = out.lower()
    return "version-script" in low or "version script" in low or "exports.map" in low


