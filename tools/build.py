def load_manifest(project):
    path = os.path.join(project, "plugin.json")
    if not os.path.isfile(path):
        raise BuildError("No plugin.json found in %s\n"
                         "  A plugin project needs plugin.json, src/<Name>.cpp and optionally ui.json.\n"
                         "  Create one with: python tools/new_plugin.py \"My Plugin\" --vendor \"Me\"" % project)
    try:
        with open(path, "r", encoding="utf-8") as fh:
            manifest = json.load(fh)
    except ValueError as e:
        raise BuildError("plugin.json is not valid JSON: %s\n  (%s)" % (e, path))
    if not isinstance(manifest, dict):
        raise BuildError("plugin.json must contain a JSON object (%s)" % path)
    for key in ("name", "manufacturer"):
        if not isinstance(manifest.get(key), str) or not manifest[key].strip():
            raise BuildError("plugin.json is missing the required string \"%s\" (%s)" % (key, path))
    if "version" not in manifest:
        warn("plugin.json has no \"version\"; assuming \"1.0.0\"")
        manifest["version"] = "1.0.0"
    return manifest


def find_sources(project):
    src_dir = os.path.join(project, "src")
    if not os.path.isdir(src_dir):
        raise BuildError("No src/ folder in %s (expected src/<Name>.cpp)" % project)
    sources = sorted(
        os.path.join(src_dir, f) for f in os.listdir(src_dir)
        if f.lower().endswith(".cpp") and os.path.isfile(os.path.join(src_dir, f))
    )
    if not sources:
        raise BuildError("No .cpp files found in %s" % src_dir)
    return sources


