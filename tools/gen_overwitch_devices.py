#!/usr/bin/env python3
"""Generate plugins/MPC Overwitch/src/ob_devices.h from Overwitch's res/devices.json.

Only Overbridge 2 / 2.1 devices (interrupt transfers) are emitted; those are the ones the
plugin's USB engine speaks. Device data comes from Overwitch (GPL-3.0-or-later).

    python tools/gen_overwitch_devices.py path/to/overwitch/res/devices.json
"""
import json, sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'plugins' / 'MPC Overwitch' / 'src' / 'ob_devices.h'


def main():
    src = Path(sys.argv[1])
    devices = [d for d in json.loads(src.read_text()) if str(d.get('version')) in ('2', '2.1')]
    lines = ['// Generated by tools/gen_overwitch_devices.py from Overwitch res/devices.json. Do not edit.',
             '// Device data: Overwitch, https://github.com/dagargo/overwitch, GPL-3.0-or-later.',
             '#pragma once', '#include <cstdint>', '', 'namespace ob {', '',
             'struct Track { const char* name; uint8_t size; };',
             'struct Device', '{',
             '    uint16_t pid;', '    const char* name;', '    bool v21;            // Overbridge 2.1: 24-bit samples',
             '    int numOutputs;      // device -> host tracks', '    const Track* outputs;',
             '    int numInputs;       // host -> device tracks', '    const Track* inputs;', '};', '']
    for i, d in enumerate(devices):
        for kind in ('output', 'input'):
            tr = d[kind + '_tracks']
            body = ', '.join('{"%s", %d}' % (t['name'].replace('"', ''), t['size']) for t in tr)
            lines.append('static const Track k%s%d[] = {%s};' % (kind.capitalize(), i, body))
    lines.append('')
    lines.append('static const Device kDevices[] = {')
    for i, d in enumerate(devices):
        lines.append('    {0x%04x, "%s", %s, %d, kOutput%d, %d, kInput%d},' % (
            d['pid'], d['name'], 'true' if str(d['version']) == '2.1' else 'false',
            len(d['output_tracks']), i, len(d['input_tracks']), i))
    lines += ['};', 'static const int kNumDevices = %d;' % len(devices), '',
              'inline const Device* findDevice(uint16_t pid)', '{',
              '    for (int i = 0; i < kNumDevices; ++i)', '        if (kDevices[i].pid == pid) return &kDevices[i];',
              '    return nullptr;', '}', '', '} // namespace ob', '']
    OUT.write_text('\n'.join(lines))
    print('wrote', OUT, '(%d devices)' % len(devices))


if __name__ == '__main__':
    main()
